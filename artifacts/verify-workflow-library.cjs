const assert = require('node:assert/strict')
const { chromium } = require('playwright')

;(async () => {
  const browser = await chromium.launch({ channel: 'msedge', headless: true })
  try {
    const page = await browser.newPage({ viewport: { width: 1366, height: 900 } })
    const errors = []
    page.on('pageerror', error => errors.push(error.message))
    await page.goto('http://127.0.0.1:5173/work-in-action')
    const filters = page.getByRole('group', { name: 'Filter by platform' })
    const cards = page.locator('.workflow-library__card')
    await filters.getByRole('button', { name: 'GHL', exact: true }).waitFor()
    assert.equal(await cards.count(), 6)
    assert.deepEqual(await filters.getByRole('button').allTextContents(), ['All workflows', 'GHL', 'n8n'])
    const receptionist = page.getByRole('link', { name: /AI Receptionist/ })
    assert.equal(await receptionist.locator('img.workflow-thumbnail-image').count(), 1)
    assert.match(await receptionist.locator('img.workflow-thumbnail-image').getAttribute('alt'), /voice receptionist answering calls/i)
    await filters.getByRole('button', { name: 'GHL', exact: true }).click()
    assert.equal(await cards.count(), 3)
    assert.deepEqual(await cards.locator('h2').allTextContents(), ['Lead Journey System', 'Appointment Care System', 'Client Welcome System'])
    assert.equal(await filters.getByRole('button', { name: 'GHL', exact: true }).getAttribute('aria-pressed'), 'true')
    await filters.getByRole('button', { name: 'n8n', exact: true }).click()
    assert.equal(await cards.count(), 3)
    assert.deepEqual(await cards.locator('h2').allTextContents(), ['AI Receptionist', 'Basic RAG System', 'HR Evaluation & Job Posting Assistant'])
    await page.getByRole('searchbox').fill('recruitment')
    assert.equal(await cards.count(), 1)
    assert.match(await cards.first().innerText(), /HR Evaluation/)
    await filters.getByRole('button', { name: 'GHL', exact: true }).click()
    assert.equal(await cards.count(), 0, 'Search is combined with platform filter')
    await page.getByRole('button', { name: 'Clear search & filters', exact: true }).click()
    assert.equal(await cards.count(), 6)
    assert.equal(await page.getByRole('searchbox').inputValue(), '')
    await page.waitForFunction(() => Array.from(document.querySelectorAll('.workflow-thumbnail-image')).every(image => image.complete && image.naturalWidth > 0))
    assert.equal(await page.locator('.workflow-library__grid').evaluate(el => getComputedStyle(el).gridTemplateColumns.split(' ').length), 2, 'Two desktop columns')
    await page.waitForTimeout(6500)
    await page.screenshot({ path: 'artifacts/workflow-library-light.png', fullPage: true })
    const lightSurface = await cards.first().evaluate(el => getComputedStyle(el).backgroundColor)
    await page.getByRole('button', { name: 'Switch to dark theme', exact: true }).click()
    await page.waitForFunction(() => document.documentElement.dataset.theme === 'dark' && !document.documentElement.dataset.themeSweep)
    const darkSurface = await cards.first().evaluate(el => getComputedStyle(el).backgroundColor)
    assert.notEqual(darkSurface, lightSurface, 'Theme changes opaque card surfaces')
    await page.screenshot({ path: 'artifacts/workflow-library-dark.png', fullPage: true })
    await filters.getByRole('button', { name: 'n8n', exact: true }).focus()
    await page.keyboard.press('Enter')
    assert.equal(await cards.count(), 3, 'Keyboard operates platform filters')
    for (const width of [320, 390]) {
      await page.setViewportSize({ width, height: 844 })
      await page.waitForTimeout(200)
      assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth))
      const first = await cards.nth(0).boundingBox()
      const second = await cards.nth(1).boundingBox()
      assert(second.y >= first.y + first.height, 'Single-column mobile cards')
      assert(await cards.first().evaluate(el => el.scrollWidth <= el.clientWidth + 1), 'Card contents fit')
    }
    await page.screenshot({ path: 'artifacts/workflow-library-mobile-dark.png', fullPage: true })
    await page.getByRole('button', { name: 'Theme and accessibility', exact: true }).click()
    await page.getByRole('switch', { name: 'Dark theme', exact: true }).click()
    await page.keyboard.press('Escape')
    await page.waitForFunction(() => document.documentElement.dataset.theme === 'light' && !document.documentElement.dataset.themeSweep)
    await page.screenshot({ path: 'artifacts/workflow-library-mobile-light.png', fullPage: true })
    await page.emulateMedia({ reducedMotion: 'reduce' })
    assert(await cards.first().evaluate(el => parseFloat(getComputedStyle(el).transitionDuration) <= 0.001), 'Reduced motion disables meaningful transition duration')
    await page.getByRole('searchbox').fill('Basic RAG')
    await cards.first().click()
    await page.waitForURL('**/work-in-action/basic-rag')
    assert.deepEqual(errors, [])
    console.log('Workflow gallery passed: platform filters, combined search/reset, accurate previews, keyboard navigation, light/dark surfaces and mobile reflow.')
  } finally { await browser.close() }
})().catch(error => { console.error(error); process.exitCode = 1 })
