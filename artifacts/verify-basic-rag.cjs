const assert = require('node:assert/strict')
const { chromium } = require('playwright')

;(async () => {
  const browser = await chromium.launch({ channel: 'msedge', headless: true })
  try {
    const page = await browser.newPage({ viewport: { width: 1366, height: 900 } })
    const errors = []
    page.on('pageerror', error => errors.push(error.message))
    await page.goto('http://127.0.0.1:5173/work-in-action')
    await page.getByRole('searchbox').fill('Basic RAG')
    assert.equal(await page.locator('.workflow-library__card').count(), 1)
    await page.locator('.workflow-library__card').click()
    await page.waitForURL('**/work-in-action/basic-rag')
    const command = page.locator('.journey-command')
    const outputs = page.locator('.rag-outputs')
    await command.getByRole('button', { name: 'Execute workflow', exact: true }).waitFor()
    assert.equal(await outputs.locator('.reception-app').count(), 0)
    const selected = await page.locator('.journey-step').boundingBox()
    const viewer = await outputs.boundingBox()
    assert(viewer.x >= selected.x + selected.width && Math.abs(viewer.y - selected.y) < 1, 'GHL-style dock placement')
    await command.getByRole('button', { name: 'Execute workflow', exact: true }).click()
    assert.equal(await outputs.locator('.reception-app').count(), 0, 'No early result while trigger runs')
    await page.locator('[data-transferring="true"]').waitFor({ state: 'attached' })
    await command.getByRole('button', { name: 'Pause' }).click()
    assert.match(await outputs.innerText(), /How much notice do I need to reschedule/)
    assert.equal(await outputs.locator('.rag-answer').count(), 0, 'Answer requires response completion')
    assert.equal(await outputs.getByRole('button', { name: 'Sources' }).count(), 0, 'Sources require retrieval completion')
    await command.getByRole('button', { name: '4× replay speed', exact: true }).click()
    await command.getByRole('button', { name: 'Resume' }).click()
    const complete = () => command.getByRole('button', { name: 'Run again' }).waitFor({ timeout: 18000 })
    await complete()
    assert.match(await outputs.locator('.rag-answer').innerText(), /at least 24 hours’ notice/)
    await outputs.getByRole('button', { name: '[1] Appointment policy.pdf · Page 2', exact: true }).click()
    assert.match(await outputs.innerText(), /Page 2 · Version v1 · Active/)
    assert.match(await outputs.locator('blockquote').innerText(), /at least 24 hours’ notice/)
    await page.getByRole('button', { name: 'Fit view', exact: true }).click()
    await page.locator('#main-content').evaluate(el => { el.scrollTop = 0 })
    await page.waitForTimeout(300)
    await page.screenshot({ path: 'artifacts/basic-rag-desktop.png', fullPage: true })
    await command.getByRole('button', { name: 'No matching source', exact: true }).click()
    assert.equal(await outputs.locator('.reception-app').count(), 0, 'Scenario resets fixtures')
    await command.getByRole('button', { name: 'Execute workflow', exact: true }).click()
    await complete()
    assert.match(await outputs.locator('.rag-answer').innerText(), /I couldn’t find a group discount policy/)
    assert.equal(await outputs.locator('.rag-citation').count(), 0, 'No invented citation')
    assert.equal(await page.locator('[data-node="rag-model"]').getAttribute('data-status'), 'Skipped')
    await outputs.getByRole('button', { name: 'Sources', exact: false }).click()
    assert.match(await outputs.innerText(), /0 matches/)
    await command.getByRole('button', { name: 'Add a document', exact: true }).click()
    await command.getByRole('button', { name: 'Execute workflow', exact: true }).click()
    await complete()
    assert.deepEqual(await outputs.locator('tbody tr td').allTextContents(), ['Appointment policy.pdf', 'v1', '3', 'Indexed'])
    assert.match(await outputs.innerText(), /No old chunks to remove/)
    await command.getByRole('button', { name: 'Update a document', exact: true }).click()
    await command.getByRole('button', { name: 'Execute workflow', exact: true }).click()
    await complete()
    assert.equal(await page.locator('[data-node="remove-vectors"]').getAttribute('data-status'), 'Skipped')
    assert.equal(await outputs.getByRole('button', { name: 'Chat', exact: false }).count(), 0)
    assert.deepEqual(await outputs.locator('tbody tr td').allTextContents(), ['Appointment policy.pdf', 'v2', '4', 'Indexed'])
    assert.match(await outputs.innerText(), /3 old v1 chunks removed; 4 v2 chunks indexed/)
    await outputs.getByRole('button', { name: 'Document chunks', exact: false }).click()
    assert.match(await outputs.locator('blockquote').innerText(), /48 hours’ notice/)
    await command.getByRole('button', { name: 'Archive a document', exact: true }).click()
    await command.getByRole('button', { name: 'Execute workflow', exact: true }).click()
    await complete()
    assert.deepEqual(await outputs.locator('tbody tr td').allTextContents(), ['Appointment policy.pdf', 'v1 (archived)', '0', 'Archived'])
    assert.equal(await outputs.getByRole('button', { name: 'Document chunks', exact: false }).count(), 0)
    assert.equal(await page.locator('[data-node="upsert-vectors"]').getAttribute('data-status'), 'Skipped')
    assert.match(await outputs.innerText(), /will not appear in future retrieval/)
    for (const width of [320, 390]) {
      await page.setViewportSize({ width, height: 844 })
      await page.waitForTimeout(200)
      assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth))
      const step = await page.locator('.journey-step').boundingBox()
      const output = await outputs.boundingBox()
      assert(output.y + 1 >= step.y + step.height, 'Mobile stacks the dock')
    }
    await page.screenshot({ path: 'artifacts/basic-rag-mobile.png', fullPage: true })
    await command.getByRole('button', { name: 'Reset', exact: true }).click()
    assert.equal(await outputs.locator('.reception-app').count(), 0)
    await page.emulateMedia({ reducedMotion: 'reduce' })
    await command.getByRole('button', { name: 'Execute workflow', exact: true }).click()
    assert.equal(await page.locator('.hl-execution-ring rect').evaluate(el => getComputedStyle(el).animationName), 'none')
    assert.deepEqual(errors, [])
    console.log('Basic RAG passed: library, cited answer, no-source fallback, document replacement/archive, progressive outputs, reset and responsive dock.')
  } finally { await browser.close() }
})().catch(error => { console.error(error); process.exitCode = 1 })
