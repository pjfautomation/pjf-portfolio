const { chromium } = require('playwright')
const assert = require('node:assert/strict')

;(async () => {
  const browser = await chromium.launch({ channel: 'msedge', headless: true })
  const page = await browser.newPage({ viewport: { width: 1366, height: 768 } })
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('http://127.0.0.1:5173/work-in-action/lead-journey')
  await page.waitForTimeout(6500)
  const output = page.locator('.journey-output')
  const progress = page.locator('.journey-progress > span')
  const run = name => page.locator('.journey-canvas').getByRole('button', { name, exact: !['Test workflow', 'Run again', 'Pause', 'Resume'].includes(name) }).click()
  const waitComplete = () => page.getByRole('button', { name: 'Run again', exact: false }).waitFor({ timeout: 12000 })
  assert.equal(await output.count(), 0, 'No sample app is rendered before execution')
  assert((await page.locator('.journey-live').boundingBox()).height >= 460, 'Output panel reserves space for the longest output')
  const geometry = await page.locator('.journey-canvas').evaluate(el => ({ scroll: el.scrollHeight, height: el.clientHeight }))
  assert(geometry.scroll <= geometry.height + 2, 'No controls are clipped by the workspace')
  await run('Test workflow')
  assert.equal(await output.count(), 0, 'Running first step does not reveal it early')
  assert.equal(await page.locator('.hl-execution-ring').count(), 1, 'Executing action has an outline animation')
  assert.equal(await page.locator('.hl-transfer').count(), 0, 'Connector does not animate before the action completes')
  await run('Pause')
  await page.waitForTimeout(80)
  const ring = page.locator('.hl-execution-ring rect')
  const ringOffset = await ring.evaluate(el => getComputedStyle(el).strokeDashoffset)
  await page.waitForTimeout(300)
  assert.equal(await ring.evaluate(el => getComputedStyle(el).strokeDashoffset), ringOffset, 'Pause freezes the execution outline')
  await run('Resume')
  await page.getByRole('button', { name: 'Form', exact: true }).waitFor()
  assert.equal(await output.count(), 1)
  assert.equal(await page.locator('.journey-output__head h3').textContent(), 'Website contact form')
  assert.equal(await page.getByRole('button', { name: 'Gmail', exact: true }).count(), 0)
  await run('Pause')
  const connector = page.locator('.hl-transfer')
  assert.equal(await connector.count(), 1, 'Connector animates after action completion')
  assert.equal(await page.locator('.hl-execution-ring').count(), 0)
  assert.equal(await page.locator('[data-node="crm"]').getAttribute('data-status'), 'Waiting', 'Next action waits for connector handoff')
  const pausedAt = await progress.textContent()
  await page.waitForTimeout(900)
  assert.equal(await progress.textContent(), pausedAt, 'Pause stops execution')
  assert.equal(await connector.evaluate(el => getComputedStyle(el).animationPlayState), 'paused')
  await run('4× replay speed')
  await run('Resume')
  await waitComplete()
  assert.equal(await page.locator('.journey-output-picker button').count(), 6)
  assert.equal(await output.count(), 1, 'Only the focused output is rendered')
  assert.match(await output.textContent(), /Book your discovery call/)
  await page.getByRole('button', { name: 'Sheets', exact: true }).click()
  assert.equal(await page.locator('.journey-sheet tbody tr').count(), 1)
  assert.match(await page.locator('.journey-sheet tbody').textContent(), /Alex Rivera/)
  await run('Fit view')
  await page.locator('[data-node="crm"]').click()
  assert.equal(await page.locator('#journey-node-title').textContent(), 'Create opportunity')
  assert.equal(await page.locator('.journey-output__head h3').textContent(), 'GoHighLevel opportunity')
  await page.locator('.journey-step__data summary').click()
  assert.match(await page.locator('.journey-step__data').textContent(), /demo_contact_104/)
  await page.locator('.journey-step__data summary').click()
  const zoom = await page.getByLabel('Canvas zoom').textContent()
  await page.getByRole('button', { name: 'Zoom in', exact: true }).click()
  assert.notEqual(await page.getByLabel('Canvas zoom').textContent(), zoom)
  await run('Fit view')
  await page.locator('.hl-builder-tabs').getByRole('button', { name: 'Execution logs', exact: true }).click()
  assert.equal(await page.locator('.hl-canvas-log li').count(), 11)
  assert.equal(await page.locator('.hl-canvas-log li button > span:last-child').filter({ hasText: 'Completed' }).count(), 10)
  await page.locator('.hl-builder-tabs').getByRole('button', { name: 'Builder', exact: true }).click()
  const stage = page.locator('.journey-canvas__stage')
  const world = page.locator('.journey-canvas__world')
  const beforePan = await world.getAttribute('style')
  await stage.focus()
  await page.keyboard.press('ArrowRight')
  assert.notEqual(await world.getAttribute('style'), beforePan)
  await run('Fit view')
  await page.locator('.journey-execution summary').click()
  assert.equal(await page.locator('.journey-execution li[data-status="Skipped"]').count(), 1)
  await page.locator('.journey-execution summary').click()
  const panelHeights = []
  for (const label of ['Form', 'CRM', 'Sheets', 'Telegram', 'WhatsApp', 'Gmail']) {
    await page.locator('.journey-output-picker').getByRole('button', { name: label, exact: true }).click()
    panelHeights.push((await page.locator('.journey-live').boundingBox()).height)
    assert(await page.locator('.journey-live__body').evaluate(el => el.scrollHeight <= el.clientHeight + 2), `${label} fits without vertical scrolling`)
    assert.equal(await page.locator('.journey-live__body').evaluate(el => getComputedStyle(el).overflowY), 'visible')
  }
  assert(Math.max(...panelHeights) - Math.min(...panelHeights) <= 1, 'Output panel height remains fixed when switching apps')
  await page.locator('.journey-output-picker').getByRole('button', { name: 'Gmail', exact: true }).click()
  await page.screenshot({ path: 'artifacts/replay-workspace-laptop-complete.png' })
  await run('Run again')
  assert.equal(await output.count(), 0, 'Run again clears prior outputs immediately')
  await run('Reset')
  await run('Needs more context')
  assert.equal(await output.count(), 0, 'Scenario change clears outputs')
  await run('Test workflow')
  await waitComplete()
  assert.equal(await page.locator('[data-node="booking"]').getAttribute('data-status'), 'Skipped')
  assert.equal(await page.locator('[data-node="nurture"]').getAttribute('data-status'), 'Completed')
  assert.match(await output.textContent(), /main bottleneck/)
  await run('Email only')
  await run('Test workflow')
  await waitComplete()
  assert.equal(await page.locator('.journey-output-picker button').count(), 5)
  assert.equal(await page.locator('[data-node="whatsapp"]').getAttribute('data-status'), 'Skipped')
  assert.equal(await page.getByRole('button', { name: 'WhatsApp', exact: true }).count(), 0)
  await page.evaluate(() => document.documentElement.dataset.theme = 'dark')
  await page.setViewportSize({ width: 1875, height: 935 })
  await page.screenshot({ path: 'artifacts/replay-workspace-dark-complete.png' })
  await page.setViewportSize({ width: 768, height: 1024 })
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth))
  await page.setViewportSize({ width: 390, height: 844 })
  await run('Reset')
  await run('Test workflow')
  await page.waitForFunction(() => document.querySelector('[data-node="route"]')?.getAttribute('data-status') === 'Running')
  await page.waitForTimeout(250)
  const activeNode = await page.locator('[data-node="route"]').boundingBox()
  const stageBox = await stage.boundingBox()
  assert(activeNode.x >= stageBox.x && activeNode.x + activeNode.width <= stageBox.x + stageBox.width, 'Active node follows into mobile viewport')
  await waitComplete()
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Mobile has no page-wide horizontal overflow')
  assert(await page.locator('.journey-live__body').evaluate(el => el.scrollHeight <= el.clientHeight + 2), 'Complete mobile email fits without vertical scrolling')
  await page.screenshot({ path: 'artifacts/replay-workspace-mobile.png', fullPage: true })
  await page.emulateMedia({ reducedMotion: 'reduce' })
  assert.equal(await output.evaluate(el => getComputedStyle(el).animationName), 'none')
  await run('Reset')
  await run('1× replay speed')
  await run('Test workflow')
  assert.equal(await page.locator('.hl-execution-ring rect').evaluate(el => getComputedStyle(el).animationName), 'none')
  await page.waitForFunction(() => document.querySelector('.hl-transfer') !== null)
  await run('Pause')
  assert.equal(await page.locator('.hl-transfer').evaluate(el => getComputedStyle(el).animationName), 'none')
  await run('Reset')
  assert.deepEqual(errors, [])
  await browser.close()
  console.log('HighLevel replay verified: outline then connector then next action, paused animations, fixed complete outputs, all scenarios, builder/logs, inspection, zoom/keyboard pan, mobile follow, themes, reduced motion.')
})().catch(error => { console.error(error); process.exit(1) })
