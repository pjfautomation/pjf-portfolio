const assert = require('node:assert/strict')
const { chromium } = require('playwright')

;(async () => {
  const browser = await chromium.launch({ channel: 'msedge', headless: true })
  const page = await browser.newPage({ viewport: { width: 1366, height: 768 } })
  try {
    await page.route('https://**/*', route => route.abort())
    await page.goto('http://127.0.0.1:5173/projects')
    await page.waitForTimeout(7000)
    await page.getByRole('button', { name: 'View Workflow systems', exact: true }).click()
    const gallery = page.locator('.automation-gallery')
    await gallery.waitFor()
    const originals = gallery.locator('article:not([aria-hidden])')
    assert.equal(await originals.count(), 11)
    assert.equal(await originals.locator('.automation-gallery__badge img').count(), 11)
    const track = gallery.locator('.automation-gallery__track')
    await page.mouse.move(0, 0)
    assert.equal(await track.evaluate(e => getComputedStyle(e).animationPlayState), 'running')
    const firstImage = gallery.getByRole('button', { name: 'Open RAG-Based AI Agent screenshot' })
    await firstImage.focus()
    assert.equal(await track.evaluate(e => getComputedStyle(e).animationPlayState), 'running')
    const firstBox = await firstImage.boundingBox()
    await page.mouse.move(firstBox.x + 80, firstBox.y + 40)
    assert.equal(await track.evaluate(e => getComputedStyle(e).animationPlayState), 'running')
    await page.mouse.click(firstBox.x + 80, firstBox.y + 40)
    const viewer = page.getByRole('dialog', { name: 'RAG-Based AI Agent screenshot', exact: true })
    await viewer.waitFor()
    assert.equal(await track.evaluate(e => getComputedStyle(e).animationPlayState), 'paused')
    await viewer.getByRole('button', { name: 'Next', exact: true }).click()
    assert.equal(await page.locator('dialog[open] h2').textContent(), 'HR Job Posting & Candidate Evaluation')
    await page.keyboard.press('ArrowLeft')
    assert.equal(await page.locator('dialog[open] h2').textContent(), 'RAG-Based AI Agent')
    await page.keyboard.press('ArrowLeft')
    assert.equal(await page.locator('dialog[open] h2').textContent(), 'Lead Follow-up & Sales Pipeline')
    await page.keyboard.press('Escape')
    assert.equal(await page.locator('dialog[open]').count(), 0)
    assert.equal(await page.getByRole('dialog', { name: 'Workflow systems', exact: true }).count(), 1)
    assert.equal(await page.locator(':focus').getAttribute('aria-label'), 'Open RAG-Based AI Agent screenshot')
    assert.equal(await track.evaluate(e => getComputedStyle(e).animationPlayState), 'running')
    await page.screenshot({ path: 'artifacts/automation-gallery-desktop.png' })
    await page.evaluate(() => localStorage.setItem('theme-mint-v1', 'dark'))
    await page.reload()
    await page.waitForTimeout(7000)
    await page.getByRole('button', { name: 'View Workflow systems', exact: true }).click()
    assert.equal(await page.locator('html').getAttribute('data-theme'), 'dark')
    await page.setViewportSize({ width: 390, height: 844 })
    await page.screenshot({ path: 'artifacts/automation-gallery-mobile.png' })
    assert.equal(await originals.count(), 11)
    const mobile = await gallery.evaluate(e => ({ width: e.clientWidth, scroll: e.scrollWidth, animation: getComputedStyle(e.querySelector('.automation-gallery__track')).animationName }))
    assert.ok(mobile.scroll <= mobile.width + 1)
    assert.equal(mobile.animation, 'none')
    await gallery.getByRole('button', { name: 'Open RAG-Based AI Agent screenshot' }).click()
    await page.locator('dialog[open] .automation-viewer__content > img').evaluate(async image => { await image.decode() })
    await page.keyboard.press('Escape')
    await page.setViewportSize({ width: 1366, height: 768 })
    await page.emulateMedia({ reducedMotion: 'reduce' })
    assert.equal(await track.evaluate(e => getComputedStyle(e).animationName), 'none')
    await gallery.getByRole('button', { name: 'Open RAG-Based AI Agent screenshot' }).click()
    await page.locator('dialog[open]').getByRole('link', { name: /Try the interactive demo/ }).click()
    await page.waitForURL('**/work-in-action/basic-rag')
    console.log('Scrolling showcase passed: 11 SVG badges, continuous hover/focus motion, click pause, close resume, navigation, mobile, reduced motion, themes and demo link.')
  } finally { await browser.close() }
})().catch(error => { console.error(error); process.exit(1) })
