const assert = require('node:assert/strict')
const { chromium } = require('playwright')

;(async () => {
  const browser = await chromium.launch({ channel: 'msedge', headless: true })
  try {
    const page = await browser.newPage({ viewport: { width: 1366, height: 900 } })
    const errors = []
    page.on('pageerror', error => errors.push(error.message))
    await page.goto('http://127.0.0.1:5173/work-in-action')
    await page.getByRole('searchbox').fill('HR Evaluation')
    assert.equal(await page.locator('.workflow-library__card').count(), 1)
    await page.locator('.workflow-library__card').click()
    await page.waitForURL('**/work-in-action/hr-assistant')
    const command = page.locator('.journey-command')
    const output = page.locator('.hr-outputs')
    await command.getByRole('button', { name: 'Execute workflow', exact: true }).waitFor()
    assert.equal(await output.locator('.reception-app').count(), 0)
    const stepBox = await page.locator('.journey-step').boundingBox()
    const outputBox = await output.boundingBox()
    assert(outputBox.x >= stepBox.x + stepBox.width && Math.abs(outputBox.y - stepBox.y) < 1)
    await command.getByRole('button', { name: 'Execute workflow', exact: true }).click()
    assert.equal(await output.locator('.reception-app').count(), 0, 'No preview before a producing step completes')
    await page.locator('[data-transferring="true"]').waitFor({ state: 'attached' })
    await command.getByRole('button', { name: 'Pause' }).click()
    assert.equal(await output.locator('.reception-app').count(), 0, 'Receiving application alone does not reveal CV analysis')
    await command.getByRole('button', { name: '4× replay speed', exact: true }).click()
    await command.getByRole('button', { name: 'Resume' }).click()
    const complete = () => command.getByRole('button', { name: 'Run again' }).waitFor({ timeout: 18000 })
    await complete()
    assert.match(await output.innerText(), /Awaiting recruiter review/)
    assert.match(await output.innerText(), /Not made/)
    assert.equal(await page.locator('[data-node="hr-calendar"]').getAttribute('data-status'), 'Skipped')
    assert.equal(await output.getByRole('button', { name: 'Gmail' }).count(), 0)
    await output.getByRole('button', { name: 'Recruiter review', exact: false }).click()
    assert.match(await output.innerText(), /Stated · CV page 1/)
    assert.match(await output.innerText(), /No hiring decision has been made/)
    await command.getByRole('button', { name: 'Ask a follow-up question', exact: true }).click()
    assert.equal(await output.locator('.reception-app').count(), 0, 'Scenario clears prior output')
    await command.getByRole('button', { name: 'Execute workflow', exact: true }).click()
    await complete()
    assert.match(await output.innerText(), /Follow-up requested/)
    await output.getByRole('button', { name: 'Gmail', exact: false }).click()
    assert.match(await output.innerText(), /Could you share an example of using a CRM/)
    assert.match(await output.innerText(), /application remains under review/)
    assert.equal(await page.locator('[data-node="hr-invite"]').getAttribute('data-status'), 'Skipped')
    await output.getByRole('button', { name: 'Recruiter review', exact: false }).click()
    assert.match(await output.innerText(), /Not stated · ask applicant/)
    await command.getByRole('button', { name: 'Approved interview', exact: true }).click()
    await command.getByRole('button', { name: 'Execute workflow', exact: true }).click()
    await complete()
    assert.match(await output.innerText(), /Interview scheduled/)
    assert.match(await output.innerText(), /Not made/)
    await output.getByRole('button', { name: 'Calendar', exact: false }).click()
    assert.match(await output.innerText(), /20 Oct 2026 · 2:00–2:30 PM/)
    assert.match(await output.innerText(), /recruiter approved/)
    await output.getByRole('button', { name: 'Gmail', exact: false }).click()
    assert.equal(await output.locator('a').getAttribute('href'), 'https://example.com/meet/interview-104')
    assert.match(await output.innerText(), /To: jordan@example.com/)
    await output.screenshot({ path: 'artifacts/hr-invitation.png' })
    await command.getByRole('button', { name: 'Draft a job posting', exact: true }).click()
    await command.getByRole('button', { name: 'Execute workflow', exact: true }).click()
    await complete()
    assert.match(await output.innerText(), /Internal draft · not publicly posted/)
    assert.equal(await page.locator('[data-node="hr-publish"]').getAttribute('data-status'), 'Skipped')
    assert.equal(await output.locator('a').count(), 0)
    await command.getByRole('button', { name: 'Approved job posting', exact: true }).click()
    await command.getByRole('button', { name: 'Execute workflow', exact: true }).click()
    await complete()
    assert.match(await output.innerText(), /approval_demo_104/)
    assert.equal(await output.locator('a').getAttribute('href'), 'https://example.com/careers/operations-assistant')
    assert.equal(await page.locator('[data-node="hr-save-draft"]').getAttribute('data-status'), 'Skipped')
    assert.equal(await output.getByRole('button', { name: 'Applicant', exact: false }).count(), 0)
    await page.getByRole('button', { name: 'Fit view', exact: true }).click()
    await page.locator('#main-content').evaluate(el => { el.scrollTop = 0 })
    await page.waitForTimeout(200)
    await page.screenshot({ path: 'artifacts/hr-desktop.png', fullPage: true })
    for (const width of [320, 390]) {
      await page.setViewportSize({ width, height: 844 })
      await page.waitForTimeout(200)
      assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth))
      const selected = await page.locator('.journey-step').boundingBox()
      const live = await output.boundingBox()
      assert(live.y + 1 >= selected.y + selected.height)
    }
    await page.screenshot({ path: 'artifacts/hr-mobile.png', fullPage: true })
    await command.getByRole('button', { name: 'Reset', exact: true }).click()
    assert.equal(await output.locator('.reception-app').count(), 0)
    await page.emulateMedia({ reducedMotion: 'reduce' })
    await command.getByRole('button', { name: 'Execute workflow', exact: true }).click()
    assert.equal(await page.locator('.hl-execution-ring rect').evaluate(el => getComputedStyle(el).animationName), 'none')
    assert.deepEqual(errors, [])
    console.log('HR assistant passed: evidence packets, missing-detail follow-up, human-approved interview and publication, draft gating, reset and responsive outputs.')
  } finally { await browser.close() }
})().catch(error => { console.error(error); process.exitCode = 1 })
