const { chromium } = require('playwright')
const assert = require('node:assert/strict')

;(async () => {
  const browser = await chromium.launch({ channel: 'msedge', headless: true })
  const page = await browser.newPage({ viewport: { width: 1875, height: 935 } })
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('http://127.0.0.1:5173/work-in-action')
  await page.waitForTimeout(6500)
  assert.equal(await page.locator('.workflow-library__card').count(), 6)
  await page.getByRole('searchbox').fill('Appointment Care')
  assert.equal(await page.locator('.workflow-library__card').count(), 1)
  await page.locator('.workflow-library__card').click()
  await page.waitForURL('**/work-in-action/appointment-care')
  assert.match(await page.locator('#journey-title').textContent(), /Appointment Care/)
  assert.equal(await page.locator('.journey-output').count(), 0)
  const run = name => page.locator('.journey-command').getByRole('button', { name, exact: !['Test workflow', 'Pause', 'Resume', 'Run again'].includes(name) }).click()
  const complete = () => page.getByRole('button', { name: 'Run again', exact: false }).waitFor({ timeout: 15000 })
  const picker = page.locator('.journey-output-picker')
  await run('4× replay speed')
  await run('Test workflow')
  assert.equal(await page.locator('.journey-output').count(), 0)
  await page.waitForFunction(() => document.querySelector('[data-node="wait24"]')?.dataset.status === 'Running')
  await run('Pause')
  assert.match(await page.locator('.journey-progress p').textContent(), /paused/)
  const paused = await page.locator('.journey-progress > span').textContent()
  await page.waitForTimeout(650)
  assert.equal(await page.locator('.journey-progress > span').textContent(), paused)
  await run('Resume')
  await complete()
  assert.equal(await page.locator('.journey-output-picker button').count(), 4)
  assert.equal(await page.locator('[data-node="reminder24"]').getAttribute('data-status'), 'Completed')
  assert.equal(await page.locator('[data-node="reminder1"]').getAttribute('data-status'), 'Completed')
  assert.equal(await page.locator('[data-node="stop"]').getAttribute('data-status'), 'Skipped')
  const heights = []
  for (const label of ['Calendar', 'Confirmation', '24-hour email', '1-hour SMS']) {
    await picker.getByRole('button', { name: label, exact: true }).click()
    await page.waitForTimeout(250)
    heights.push((await page.locator('.journey-live').boundingBox()).height)
    assert(await page.locator('.journey-live__body').evaluate(el => el.scrollHeight <= el.clientHeight + 2), `${label} fits without output scrolling`)
  }
  assert(Math.max(...heights) - Math.min(...heights) < 1)
  await picker.getByRole('button', { name: 'Calendar', exact: true }).click()
  assert.match(await page.locator('.appointment-clock').textContent(), /22 Oct · 9:00 AM/)
  await page.getByRole('button', { name: 'Fit view', exact: true }).click()
  await page.waitForTimeout(300)
  await page.screenshot({ path: 'artifacts/appointment-care-overview.png' })
  await run('Cancelled appointment')
  assert.equal(await page.locator('.journey-output').count(), 0)
  await run('Test workflow')
  await complete()
  assert.equal(await picker.getByRole('button').count(), 3)
  assert.equal(await page.locator('[data-node="reminder24"]').getAttribute('data-status'), 'Skipped')
  assert.equal(await page.locator('[data-node="reminder1"]').getAttribute('data-status'), 'Skipped')
  assert.equal(await page.locator('[data-node="wait24"]').getAttribute('data-status'), 'Interrupted')
  assert.equal(await page.locator('[data-node="status24"]').getAttribute('data-status'), 'Skipped')
  assert.equal(await picker.getByRole('button', { name: '24-hour email', exact: true }).count(), 0)
  assert.equal(await picker.getByRole('button', { name: '1-hour SMS', exact: true }).count(), 0)
  assert.match(await page.locator('.journey-output').textContent(), /Reminder workflow stopped/)
  await picker.getByRole('button', { name: 'Calendar', exact: true }).click()
  assert.equal(await page.locator('.appointment-calendar__top > span').textContent(), 'Cancelled')
  await run('Last-minute booking')
  await run('Test workflow')
  await complete()
  assert.equal(await picker.getByRole('button').count(), 3)
  assert.equal(await page.locator('[data-node="wait24"]').getAttribute('data-status'), 'Completed')
  assert.equal(await page.locator('[data-node="status24"]').getAttribute('data-status'), 'Skipped')
  assert.equal(await page.locator('[data-node="reminder24"]').getAttribute('data-status'), 'Skipped')
  assert.equal(await page.locator('[data-node="reminder1"]').getAttribute('data-status'), 'Completed')
  await picker.getByRole('button', { name: 'Calendar', exact: true }).click()
  assert.match(await page.locator('.appointment-facts').textContent(), /2 hours before/)
  await page.getByRole('button', { name: 'Switch to dark theme', exact: true }).click()
  await page.waitForTimeout(300)
  await page.screenshot({ path: 'artifacts/appointment-care-dark.png' })
  await page.setViewportSize({ width: 390, height: 844 })
  await run('Upcoming appointment')
  await run('Test workflow')
  await complete()
  for (const label of ['Calendar', 'Confirmation', '24-hour email', '1-hour SMS']) {
    await picker.getByRole('button', { name: label, exact: true }).click()
    await page.waitForTimeout(250)
    assert(await page.locator('.journey-live__body').evaluate(el => el.scrollHeight <= el.clientHeight + 2), `Mobile ${label} fits`)
  }
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth))
  const reminderBounds = await page.locator('[data-node="reminder1"]').boundingBox()
  const controlBounds = await page.locator('.hl-stage-controls').boundingBox()
  assert(reminderBounds.y + reminderBounds.height < controlBounds.y, 'Active reminder remains above floating canvas controls')
  await page.screenshot({ path: 'artifacts/appointment-care-mobile.png', fullPage: true })
  await page.emulateMedia({ reducedMotion: 'reduce' })
  assert.equal(await page.locator('.journey-output').evaluate(el => getComputedStyle(el).animationName), 'none')
  await run('Reset')
  assert.equal(await page.locator('.journey-output').count(), 0)
  await page.getByRole('link', { name: 'All workflows', exact: false }).click()
  await page.getByRole('searchbox').fill('Lead')
  await page.locator('.workflow-library__card').click()
  assert.match(await page.locator('#journey-title').textContent(), /Lead Journey/)
  assert.equal(await page.getByRole('button', { name: 'Qualified lead', exact: true }).getAttribute('aria-pressed'), 'true', 'Route navigation resets the scenario to the correct workflow default')
  assert.deepEqual(errors, [])
  await browser.close()
  console.log('Appointment Care verified: library navigation, all three branches, reminder suppression, fast-forwarded waits, pause/reset, complete fixed outputs, themes, mobile, reduced motion and workflow switching.')
})().catch(error => { console.error(error); process.exit(1) })
